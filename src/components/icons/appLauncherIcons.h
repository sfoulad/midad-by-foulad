// gen_icons.py, which targets the separate FreeInkUI Bitmap path and does not
// pre-rotate).
//
// Files has no entry here: it reuses FolderIcon (components/icons/folder.h),
// already 32x32 and correctly oriented for the same drawIcon() call.

